package de.tum.cit.aet.hephaestus;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import de.tum.cit.aet.hephaestus.testconfig.PostgreSQLTestContainer;
import de.tum.cit.aet.hephaestus.testconfig.PostgreSQLTestContainer.TestDatabase;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.Objects;
import liquibase.Contexts;
import liquibase.Liquibase;
import liquibase.database.DatabaseFactory;
import liquibase.database.jvm.JdbcConnection;
import liquibase.resource.ClassLoaderResourceAccessor;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

@Tag("database")
class PracticeSourceContractMigrationTest {
    private static final String CHANGELOG = "db/changelog/1793196763354_changelog.xml";
    private static final TestDatabase DATABASE =
            PostgreSQLTestContainer.createDatabase("practice_source_contract_migration");
    private static final JsonMapper MAPPER = JsonMapper.builder().build();

    @Test
    void shouldUpgradeCurrentPinsAndComparisonBasesWithoutChangingCustomWorkOrHistory() throws Exception {
        execute("""
                CREATE TABLE practice_version (
                    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
                    workspace_id bigint NOT NULL, practice_id bigint NOT NULL, number integer NOT NULL,
                    definition jsonb NOT NULL, created_at timestamptz NOT NULL,
                    UNIQUE (practice_id, number));
                CREATE TABLE practice (
                    id bigint PRIMARY KEY, workspace_id bigint NOT NULL, current_version_id bigint NOT NULL,
                    catalog_base jsonb, updated_at timestamptz NOT NULL);
                CREATE TABLE catalog_entry (entry_type text, slug text, definition jsonb, base jsonb);
                INSERT INTO practice_version VALUES
                    (101,10,1,2,'{"criteria":"Keep my criterion.\\n  Keep the whitespace.\\n","script":"custom-program.ts",
                        "reads":{"contract":"2.0.0","sources":[
                            {"source":"scm.pull-request.core","need":"REQUIRED"},
                            {"source":"scm.pull-request.checks","need":"REQUIRED"}]},
                        "scan":{"reads":{"contract":"2.0.0","sources":[{"source":"scm.repository.tree","need":"REQUIRED"}]}}}',now()),
                    (102,10,1,7,'{"reads":{"contract":"2.0.0","sources":[]},"criteria":"Historical"}',now()),
                    (201,20,2,1,'{"criteria":"Slack stays Slack","reads":{"contract":"2.0.0","sources":[
                        {"source":"slack.conversation.thread","need":"REQUIRED"}]}}',now()),
                    (301,20,3,1,'{"criteria":"Already current","reads":{"contract":"3.0.0","sources":[]}}',now());
                INSERT INTO practice SELECT practice_id, workspace_id, id,
                    jsonb_build_object('kind','scm.pull_request','definition',definition),now()
                    FROM practice_version WHERE id IN (101,201,301);
                UPDATE practice SET catalog_base=jsonb_set(catalog_base,'{definition,reads,contract}','"2.0.0"') WHERE id=3;
                INSERT INTO catalog_entry SELECT 'PRACTICE','custom',catalog_base,catalog_base FROM practice WHERE id=1;
                INSERT INTO catalog_entry VALUES ('GROUP','group','{"name":"Group"}','{"name":"Original group"}');
                """);
        JsonNode original = json("SELECT definition FROM practice_version WHERE id=101");
        JsonNode alreadyCurrent = current(3);
        JsonNode group = json("SELECT definition FROM catalog_entry WHERE entry_type='GROUP'");

        try (Liquibase liquibase = liquibase()) {
            liquibase.update(new Contexts());
        }

        JsonNode upgraded = current(1);
        assertThat(upgraded.path("criteria")).isEqualTo(original.path("criteria"));
        assertThat(upgraded.path("script")).isEqualTo(original.path("script"));
        assertThat(upgraded.at("/reads/contract").asString()).isEqualTo("3.0.0");
        assertThat(upgraded.at("/reads/sources"))
                .containsExactly(
                        original.at("/reads/sources/0"),
                        original.at("/reads/sources/1"),
                        MAPPER.readTree("{\"source\":\"scm.review-threads\",\"need\":\"OPTIONAL\"}"));
        assertThat(upgraded.at("/scan/reads/contract").asString()).isEqualTo("3.0.0");
        assertThat(upgraded.at("/scan/reads/sources")).isEqualTo(original.at("/scan/reads/sources"));
        assertThat(
                        json("SELECT to_jsonb(number) FROM practice_version WHERE id=(SELECT current_version_id FROM practice WHERE id=1)")
                                .asInt())
                .isEqualTo(8);
        assertThat(json("SELECT definition FROM practice_version WHERE id=101")).isEqualTo(original);
        assertThat(json("SELECT definition FROM practice_version WHERE id=102")
                        .at("/reads/contract")
                        .asString())
                .isEqualTo("2.0.0");
        assertThat(current(2).at("/reads/sources")).hasSize(1);
        assertThat(current(2).at("/reads/contract").asString()).isEqualTo("3.0.0");
        assertThat(current(3)).isEqualTo(alreadyCurrent);
        assertThat(json("SELECT catalog_base FROM practice WHERE id=3")
                        .at("/definition/reads/contract")
                        .asString())
                .isEqualTo("3.0.0");
        assertThat(json("SELECT catalog_base FROM practice WHERE id=1").path("definition"))
                .isEqualTo(upgraded);
        assertThat(json("SELECT definition FROM catalog_entry WHERE entry_type='PRACTICE'")
                        .path("definition"))
                .isEqualTo(upgraded);
        assertThat(json("SELECT base FROM catalog_entry WHERE entry_type='PRACTICE'")
                        .path("definition"))
                .isEqualTo(upgraded);
        assertThat(json("SELECT definition FROM catalog_entry WHERE entry_type='GROUP'"))
                .isEqualTo(group);
        assertThat(json("SELECT to_jsonb(count(*)) FROM practice_version").asInt())
                .isEqualTo(6);
        assertThat(
                        json("SELECT to_jsonb(count(*)) FROM practice p JOIN practice_version v ON v.id=p.current_version_id WHERE p.workspace_id<>v.workspace_id")
                                .asInt())
                .isZero();

        try (Liquibase liquibase = liquibase()) {
            liquibase.update(new Contexts());
            assertThat(json("SELECT to_jsonb(count(*)) FROM practice_version").asInt())
                    .isEqualTo(6);
            assertThatThrownBy(() -> liquibase.rollback(1, ""))
                    .hasStackTraceContaining("Restore the verified pre-upgrade backup");
        }
    }

    private static JsonNode current(long practice) throws SQLException {
        return json(
                "SELECT v.definition FROM practice p JOIN practice_version v ON v.id=p.current_version_id WHERE p.id="
                        + practice);
    }

    private static JsonNode json(String query) throws SQLException {
        try (Connection connection = connect();
                var statement = connection.createStatement();
                var rows = statement.executeQuery(query)) {
            assertThat(rows.next()).isTrue();
            return MAPPER.readTree(Objects.requireNonNull(rows.getString(1)));
        }
    }

    private static void execute(String sql) throws SQLException {
        try (Connection connection = connect();
                var statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private static Connection connect() throws SQLException {
        return DriverManager.getConnection(DATABASE.jdbcUrl(), DATABASE.username(), DATABASE.password());
    }

    private static Liquibase liquibase() throws Exception {
        var database = DatabaseFactory.getInstance().findCorrectDatabaseImplementation(new JdbcConnection(connect()));
        return new Liquibase(CHANGELOG, new ClassLoaderResourceAccessor(), database);
    }
}

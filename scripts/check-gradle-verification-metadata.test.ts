import assert from "node:assert/strict";
import { test } from "node:test";

import { staleComponents, withoutComponents } from "./check-gradle-verification-metadata.ts";

const metadata = `<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata>
   <configuration>
      <verify-metadata>true</verify-metadata>
   </configuration>
   <components>
      <component group="com.example" name="kept" version="1.0">
         <artifact name="kept-1.0.jar">
            <sha256 value="aa" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="com.example" name="kept" version="0.9">
         <artifact name="kept-0.9.pom">
            <sha256 value="bb" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="org.gradle" name="github-dependency-graph-gradle-plugin" version="1.4.2">
         <artifact name="github-dependency-graph-gradle-plugin-1.4.2.jar">
            <sha256 value="cc" origin="Generated by Gradle"/>
         </artifact>
      </component>
   </components>
</verification-metadata>
`;

void test("reports a version that the build did not download", () => {
	assert.deepEqual(staleComponents(metadata, new Set(["com.example:kept:1.0"])), [
		"com.example:kept:0.9",
	]);
});

void test("keeps the plugin that the dependency-graph workflows inject", () => {
	assert.deepEqual(
		staleComponents(metadata, new Set(["com.example:kept:1.0", "com.example:kept:0.9"])),
		[],
	);
});

void test("removes only the stale component blocks", () => {
	const pruned = withoutComponents(metadata, new Set(["com.example:kept:0.9"]));
	assert.ok(!pruned.includes('version="0.9"'));
	assert.ok(pruned.includes('name="kept" version="1.0"'));
	assert.ok(pruned.includes("github-dependency-graph-gradle-plugin"));
	assert.equal(pruned.split("\n").length, metadata.split("\n").length - 5);
});

void test("keeps only the newest injected plugin version", () => {
	const older = metadata.replace(
		"   </components>",
		`      <component group="org.gradle" name="github-dependency-graph-gradle-plugin" version="1.10.0">
         <artifact name="github-dependency-graph-gradle-plugin-1.10.0.jar">
            <sha256 value="dd" origin="Generated by Gradle"/>
         </artifact>
      </component>
   </components>`,
	);
	assert.deepEqual(
		staleComponents(older, new Set(["com.example:kept:1.0", "com.example:kept:0.9"])),
		["org.gradle:github-dependency-graph-gradle-plugin:1.4.2"],
	);
});

void test("refuses a file that is not in Gradle's layout", () => {
	assert.throws(
		() =>
			staleComponents(
				metadata.replace(
					'      <component group="com.example" name="kept" version="0.9">',
					'<component group="com.example" name="kept" version="0.9">',
				),
				new Set(),
			),
		/not in the layout Gradle writes/u,
	);
});

/**
 * Writes the admin bundle of a managed cluster, deploy/platform/hephaestus-cluster-admin.yaml: every
 * cluster-scoped object that a release without cluster-admin needs (docs/admin/managed-cluster.mdx
 * § Admin handoff). The cluster's admins apply it once for each release.
 *
 * - The four agent-sandbox CRDs, copied unchanged from k3s-agent-sandbox.yaml, whose pin line
 *   scan-platform-images.ts checks against the upstream release.
 * - The three PriorityClasses that profiles/cluster.yaml names, at the values of templates/priority.yaml.
 * - One read-only ClusterRole for the controller that runs in the release namespace, and its binding.
 *   The controller v1.0.10 has no namespace option, so its caches list and watch in all namespaces.
 *   Each write right is in a Role of the chart (templates/agent-sandbox-controller.yaml).
 *
 * The binding names the ServiceAccount of the release `hephaestus` in the namespace `hephaestus`.
 *
 *   node scripts/cluster-admin-bundle.ts [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { parseArgs } from "node:util";

const ROOT = path.join(import.meta.dirname, "..");
const PLATFORM = path.join(ROOT, "deploy", "platform");
export const BUNDLE = path.join(PLATFORM, "hephaestus-cluster-admin.yaml");
const AGENT_SANDBOX = path.join(PLATFORM, "k3s-agent-sandbox.yaml");
/** The release and namespace that the admin guide installs, so the binding's subject is fixed. */
export const CONTROLLER = { name: "hephaestus-agent-sandbox-controller", namespace: "hephaestus" };
export const READ_ROLE = "hephaestus-agent-sandbox-read";

const HEADER = `# The admin bundle of a managed cluster: every cluster-scoped object of a Hephaestus release that has
# no cluster-admin (docs/admin/managed-cluster.mdx § Admin handoff). Apply it once for each release:
#
#   kubectl apply --server-side -f hephaestus-cluster-admin.yaml
#
# Generated by scripts/cluster-admin-bundle.ts from k3s-agent-sandbox.yaml: do not edit.
`;

const OWN = `apiVersion: scheduling.k8s.io/v1
kind: PriorityClass
metadata:
  name: hephaestus-roles
value: 100000
globalDefault: false
preemptionPolicy: PreemptLowerPriority
description: "Hephaestus roles, the conversation loop, PostgreSQL and NATS"
---
apiVersion: scheduling.k8s.io/v1
kind: PriorityClass
metadata:
  name: hephaestus-conversations
value: 10000
globalDefault: false
preemptionPolicy: PreemptLowerPriority
description: "Hephaestus tools Pods of conversations"
---
apiVersion: scheduling.k8s.io/v1
kind: PriorityClass
metadata:
  name: hephaestus-reviews
value: 1000
globalDefault: false
preemptionPolicy: Never
description: "Hephaestus review sandboxes and isolation probes"
---
# Read only. The agent-sandbox controller in the namespace ${CONTROLLER.namespace} lists and watches these kinds
# in all namespaces. It writes only in the release's sandbox namespace, through a Role.
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRole
metadata:
  name: ${READ_ROLE}
rules:
  - apiGroups: [""]
    resources: [pods, services]
    verbs: [get, list, watch]
  - apiGroups: [agents.x-k8s.io]
    resources: [sandboxes]
    verbs: [get, list, watch]
  - apiGroups: [extensions.agents.x-k8s.io]
    resources: [sandboxclaims, sandboxtemplates, sandboxwarmpools]
    verbs: [get, list, watch]
  - apiGroups: [networking.k8s.io]
    resources: [networkpolicies]
    verbs: [get, list, watch]
---
apiVersion: rbac.authorization.k8s.io/v1
kind: ClusterRoleBinding
metadata:
  name: ${READ_ROLE}
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: ${READ_ROLE}
subjects:
  - kind: ServiceAccount
    name: ${CONTROLLER.name}
    namespace: ${CONTROLLER.namespace}
`;

/** The CRD documents of the pinned agent-sandbox manifest, as their text. */
function crds(manifest: string): string[] {
	return manifest
		.split(/^---\n/mu)
		.filter((document) => /^kind: CustomResourceDefinition$/mu.test(document))
		.map((document) => document.replace(/^(?:#.*\n)+/u, "").trimEnd());
}

export function bundle(): string {
	const documents = crds(readFileSync(AGENT_SANDBOX, "utf8"));
	if (documents.length !== 4) {
		throw new Error(`k3s-agent-sandbox.yaml has ${documents.length} CRDs, not 4`);
	}
	return `${HEADER}${[...documents, OWN.trimEnd()].join("\n---\n")}\n`;
}

if (import.meta.main) {
	const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });
	const expected = bundle();
	if (values.check) {
		if (readFileSync(BUNDLE, "utf8") !== expected) {
			throw new Error(
				"hephaestus-cluster-admin.yaml is stale: run node scripts/cluster-admin-bundle.ts",
			);
		}
	} else {
		writeFileSync(BUNDLE, expected);
	}
}
